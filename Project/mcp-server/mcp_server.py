def call_tool(name: str, arguments: dict):
    if name == "generate_diff":
        old_conf = arguments.get("old_config", "")
        new_conf = arguments.get("new_config", "")
        res = diff.generate_config_diff(old_conf, new_conf)
        return {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps(res, indent=2)
                }
            ]
        }
        
    elif name == "risk_review":
        diff_data = arguments.get("diff_json", {})
        res = risk_engine.analyze_config_risks(diff_data)
        return {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps(res, indent=2)
                }
            ]
        }
        
    elif name == "analyze_config":
        content = arguments.get("config_content", "")
        # Run a quick diff against empty config to get rule triggers on the whole file
        diff_res = diff.generate_config_diff("", content)
        rules_res = risk_engine.analyze_config_risks(diff_res["diff_json"])
        ip_findings = reputation.analyze_config_ips(content)
        
        analysis_res = {
            "risk_score": rules_res["risk_score"],
            "risk_level": rules_res["risk_level"],
            "rules_triggered": rules_res["rules_triggered"],
            "public_ips_detected": ip_findings
        }
        return {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps(analysis_res, indent=2)
                }
            ]
        }
        
    elif name == "generate_report":
        title = arguments.get("title", "MCP Review")
        old_conf = arguments.get("old_config", "")
        new_conf = arguments.get("new_config", "")
        
        diff_res = diff.generate_config_diff(old_conf, new_conf)
        rules_res = risk_engine.analyze_config_risks(diff_res["diff_json"])
        ip_findings = reputation.analyze_config_ips(new_conf)
        
        ai_review = workflow.run_agent_workflow(
            raw_diff=diff_res["raw_diff"],
            triggered_rules=rules_res["rules_triggered"],
            ip_findings=ip_findings
        )
        
        report_data = {
            "title": title,
            "status": "reviewed" if rules_res["risk_score"] > 20 else "approved",
            "risk_score": rules_res["risk_score"],
            "risk_level": rules_res["risk_level"],
            "stats": diff_res["diff_json"]["statistics"],
            "rules_triggered": rules_res["rules_triggered"],
            "ip_reputation": ip_findings,
            "executive_summary": ai_review.get("executive_summary", ""),
            "approval_recommendation": ai_review.get("approval_recommendation", ""),
            "ai_risk_analysis": ai_review.get("ai_risk_analysis", ""),
            "reviewer_notes": ai_review.get("reviewer_notes", "")
        }
        return {
            "content": [
                {
                    "type": "text",
                    "text": json.dumps(report_data, indent=2)
                }
            ]
        }
    else:
        raise ValueError(f"Unknown tool name: {name}")

def serve():
    log_err("Starting Network Config Reviewer MCP Server...")
    for line in sys.stdin:
        if not line.strip():
            continue
        try:
            req = json.loads(line)
            method = req.get("method")
            req_id = req.get("id")
            
            if method == "initialize":
                res = {
                    "jsonrpc": "2.0",
                    "id": req_id,
                    "result": {
                        "protocolVersion": "2024-11-05",
                        "capabilities": {
                            "tools": {}
                        },
                        "serverInfo": {
                            "name": "Network Config Reviewer MCP Server",
                            "version": "1.0.0"
                        }
                    }
                }
                print(json.dumps(res))
                sys.stdout.flush()
                
            elif method == "tools/list":
                res = {
                    "jsonrpc": "2.0",
                    "id": req_id,
                    "result": get_tools_list()
                }
                print(json.dumps(res))
                sys.stdout.flush()
                
            elif method == "tools/call":
                params = req.get("params", {})
                name = params.get("name")
                arguments = params.get("arguments", {})
                
                try:
                    tool_res = call_tool(name, arguments)
                    res = {
                        "jsonrpc": "2.0",
                        "id": req_id,
                        "result": tool_res
                    }
                except Exception as ex:
                    res = {
                        "jsonrpc": "2.0",
                        "id": req_id,
                        "error": {
                            "code": -32603,
                            "message": str(ex),
                            "data": traceback.format_exc()
                        }
                    }
                print(json.dumps(res))
                sys.stdout.flush()
            else:
                # Unknown method
                if req_id is not None:
                    res = {
                        "jsonrpc": "2.0",
                        "id": req_id,
                        "error": {
                            "code": -32601,
                            "message": f"Method not found: {method}"
                        }
                    }
                    print(json.dumps(res))
                    sys.stdout.flush()
        except Exception as e:
            log_err(f"Error processing input line: {str(e)}\n{traceback.format_exc()}")

if __name__ == "__main__":
    serve()
